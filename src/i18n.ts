// نظام اللغات: العربية الفصحى + الإنجليزية — بدون أي لهجات عامية.
export type Language = "ar" | "en";

const LANG_KEY = "opencode-language";

const LANGUAGE_META: Record<Language, { dir: "rtl" | "ltr" }> = {
  ar: { dir: "rtl" },
  en: { dir: "ltr" },
};

export function getSavedLanguage(): Language {
  try {
    const raw = localStorage.getItem(LANG_KEY);
    if (raw === "ar" || raw === "en") {
      return raw;
    }
    const nav = (navigator.language || "").toLowerCase();
    if (nav.startsWith("ar")) {
      return "ar";
    }
    if (nav.startsWith("en")) {
      return "en";
    }
  } catch {
    // التخزين غير متاح — استخدام الافتراضي.
  }
  return "ar";
}

export function saveLanguage(lang: Language): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // تجاهل — التخزين غير متاح.
  }
}

export function applyLanguage(lang: Language): void {
  const meta = LANGUAGE_META[lang];
  document.documentElement.lang = lang === "ar" ? "ar" : "en";
  document.documentElement.dir = meta.dir;
  document.title = "RemoteCode";
}

export function localeOf(lang: Language): string {
  return lang === "ar" ? "ar" : "en-US";
}

