// دمج نص ملصوق من الحافظة في آخر المسودة.
//
// المسودة ممكن توصل هنا فاضية شكليًا لكن قيمتها أسطر فاضية بس: حقل الكتابة
// contenteditable، وكروم بيرجّع `innerText` بـ "\n" لما يبقى فيه <br> وحده
// (اللي بيفضل بعد مسح آخر حرف أو أول ما تفوكس الحقل). من غير المعالجة دي كان
// `/\s$/` بيلقط الـ "\n" فالنص الملصوق ينزل سطر جديد تحت فراغ مش مقصود.
//
// القاعدة: مسودة فاضية بالكامل (مسافات/أسطر بس) بيتحل النص مكانها؛ مسودة
// فيها نص حقيقي بنفصل بمسافة إلا لو آخر حرف مسافة أصلًا.
export function appendClipboardText(current: string, text: string): string {
  if (!current.trim()) {
    return text
  }
  return /\s$/.test(current) ? current + text : `${current} ${text}`
}
